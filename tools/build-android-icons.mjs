// Turns the Lucide icons the web UI bundles (server/wwwroot/js/icons.mjs) into Android vector
// drawables for the widgets: android/app/src/main/res/drawable/lc_<name>.xml. Run from tools/.
import fs from 'fs';
import { ICONS } from '../server/wwwroot/js/icons.mjs';

const out = '../android/app/src/main/res/drawable';
fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(out)) if (f.startsWith('lc_')) fs.unlinkSync(`${out}/${f}`);

const attrs = s => Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));
const n = v => +(v ?? 0);

function toPath(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline': return 'M' + a.points.trim().split(/[\s,]+/).reduce((acc, v, i) => acc + (i && i % 2 === 0 ? 'L' : i ? ' ' : '') + v, '');
    case 'polygon': return toPath('polyline', a) + 'Z';
    case 'circle': { const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)]; return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`; }
    case 'ellipse': { const [cx, cy, rx, ry] = [n(a.cx), n(a.cy), n(a.rx), n(a.ry)]; return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`; }
    case 'rect': {
      const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
      const r = Math.min(n(a.rx ?? a.ry), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
  }
  return null;
}

// Android's path parser can't split arc flags that SVG allows run together ("a2 2 0 0022 17" is
// rx ry rotation large sweep x y = 2 2 0 0 0 22 17), so every path is re-tokenised and written out spaced.
function normalise(d) {
  const out = [];
  const re = /([MmLlHhVvCcSsQqTtAaZz])|(-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)/g;
  let i = 0, cmd = '', argi = 0;
  const skip = () => { while (i < d.length && /[\s,]/.test(d[i])) i++; };
  while (true) {
    skip();
    if (i >= d.length) break;
    if (/[A-Za-z]/.test(d[i])) { cmd = d[i++]; argi = 0; out.push(cmd); continue; }
    // Arc flags (4th and 5th of every 7 arguments) are a single 0 or 1 digit.
    if ((cmd === 'a' || cmd === 'A') && (argi % 7 === 3 || argi % 7 === 4)) { out.push(d[i++]); argi++; continue; }
    re.lastIndex = i;
    const m = re.exec(d);
    if (!m || m.index !== i || !m[2]) throw new Error(`bad path near ${i}: ${d}`);
    out.push(m[2]); i = re.lastIndex; argi++;
  }
  return out.join(' ');
}

let count = 0;
for (const [name, svg] of Object.entries(ICONS)) {
  const paths = [...svg.matchAll(/<(\w+)\s([^>]*?)\/?>/g)].map(m => toPath(m[1], attrs(m[2]))).filter(Boolean).map(normalise);
  const body = paths.map(d => `  <path android:pathData="${d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />`).join('\n');
  fs.writeFileSync(`${out}/lc_${name.replace(/-/g, '_')}.xml`,
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Lucide (ISC), generated by tools/build-android-icons.mjs -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n${body}\n</vector>\n`);
  count++;
}
console.log('android icons:', count);
